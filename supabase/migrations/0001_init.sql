-- Kilimanjaro Pazuri — initial schema.
--
-- Apply with the Supabase CLI (`supabase db push`), or paste into the SQL
-- editor. The application also applies this on boot, so a fresh project needs
-- nothing done by hand.
--
-- Every table lives in `public` but is reached only by the server, using the
-- Postgres connection string. RLS is enabled and left without policies, so
-- the anon and authenticated API keys can read nothing even if they leak;
-- the connection string bypasses RLS as the table owner.

create table if not exists rooms (
	id           bigint generated by default as identity primary key,
	slug         text    not null unique,
	name         text    not null,
	summary      text    not null,
	rate_usd     integer not null check (rate_usd >= 0),
	image        text    not null,
	guests       text    not null default 'To be confirmed',
	bed          text    not null default 'To be confirmed',
	bathroom     text    not null default 'Private',
	is_available boolean not null default true,
	position     integer not null default 0
);

create table if not exists enquiries (
	id         bigint generated by default as identity primary key,
	kind       text        not null check (kind in ('booking', 'contact')),
	name       text        not null,
	email      text        not null,
	phone      text,
	room_slug  text,
	check_in   date,
	check_out  date,
	guests     integer     check (guests is null or (guests >= 1 and guests <= 20)),
	message    text,
	status     text        not null default 'new'
	                       check (status in ('new', 'read', 'replied', 'archived')),
	created_at timestamptz not null default now()
);

create index if not exists idx_enquiries_created on enquiries (created_at desc);
create index if not exists idx_enquiries_status  on enquiries (status);

create table if not exists gallery_images (
	id       bigint generated by default as identity primary key,
	src      text    not null unique,
	alt      text    not null,
	grouping text    not null,
	position integer not null default 0
);

-- Admin sign-in sessions. Cookie-based, so the row is the whole session.
create table if not exists sessions (
	id         text        primary key,
	username   text        not null,
	expires_at timestamptz not null
);

create index if not exists idx_sessions_expires on sessions (expires_at);

alter table rooms          enable row level security;
alter table enquiries      enable row level security;
alter table gallery_images enable row level security;
alter table sessions       enable row level security;
