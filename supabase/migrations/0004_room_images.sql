-- Several photographs per room, one of them featured.
--
-- rooms.image stays as the featured photograph so every card, listing and
-- share preview keeps working unchanged; this table holds the full set and
-- decides which one that is.

create table if not exists room_images (
	id          bigint generated by default as identity primary key,
	room_slug   text    not null references rooms (slug) on delete cascade,
	src         text    not null,
	alt         text    not null default '',
	position    integer not null default 0,
	is_featured boolean not null default false
);

create index if not exists idx_room_images_room on room_images (room_slug, position);

-- At most one featured photograph per room, enforced by the database rather
-- than by remembering to clear the old one.
create unique index if not exists idx_room_images_featured
	on room_images (room_slug) where is_featured;

-- Carry each room's existing photograph across as its featured one.
insert into room_images (room_slug, src, alt, position, is_featured)
select r.slug, r.image, r.name, 0, true
  from rooms r
 where not exists (select 1 from room_images i where i.room_slug = r.slug);

alter table room_images enable row level security;
