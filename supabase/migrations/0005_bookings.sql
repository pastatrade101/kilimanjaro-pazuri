-- Room bookings, and the nights the villa closes off itself.
--
-- Both live in one table because they compete for the same thing — a room on
-- a given night — and one table can carry one constraint that settles it. A
-- `kind` tells them apart: a 'booking' came from a guest and has their
-- details; a 'block' is the owner taking nights off sale.
--
-- Dates are half-open, `[check_in, check_out)`: the morning a guest leaves,
-- the room is free for the next arrival. That is how a hotel counts, and it
-- means two stays that merely touch do not read as an overlap.

create extension if not exists btree_gist;

create table if not exists bookings (
	id          bigint generated by default as identity primary key,
	reference   text    not null unique,
	kind        text    not null default 'booking',
	room_slug   text    not null references rooms (slug) on delete restrict,
	check_in    date    not null,
	check_out   date    not null,
	guests      integer not null default 1,
	guest_name  text,
	email       text,
	phone       text,
	message     text    not null default '',
	-- The nightly rate is copied in, not joined: what the guest was quoted
	-- must survive the owner changing the room's price afterwards.
	rate_usd    integer not null default 0,
	total_usd   integer not null default 0,
	status      text    not null default 'pending',
	note        text    not null default '',
	created_at  timestamptz not null default now(),
	updated_at  timestamptz not null default now(),

	constraint bookings_kind      check (kind in ('booking', 'block')),
	constraint bookings_status    check (status in ('pending', 'confirmed', 'declined', 'cancelled', 'blocked')),
	constraint bookings_dates     check (check_out > check_in),
	constraint bookings_guests    check (guests between 1 and 20),
	-- A guest booking must say who it is for; a block needs nobody.
	constraint bookings_guest_identified check (
		kind <> 'booking' or (guest_name is not null and email is not null)
	)
);

/*
 * The whole point of this file.
 *
 * Checking availability and then inserting is a race: two guests asking for
 * the same week at the same moment both read "free" and both write. This
 * constraint makes the overlap itself illegal, so the second write fails
 * (SQLSTATE 23P01) no matter how close together they arrive. Only rows that
 * actually hold the room take part — a declined or cancelled booking frees
 * its nights again.
 */
create index if not exists idx_bookings_room_dates on bookings (room_slug, check_in, check_out);

do $$
begin
	if not exists (
		select 1 from pg_constraint where conname = 'bookings_no_overlap'
	) then
		alter table bookings add constraint bookings_no_overlap
			exclude using gist (
				room_slug with =,
				daterange(check_in, check_out, '[)') with &&
			) where (status in ('pending', 'confirmed', 'blocked'));
	end if;
end
$$;

create index if not exists idx_bookings_status  on bookings (status, check_in);
create index if not exists idx_bookings_created on bookings (created_at desc);

alter table bookings enable row level security;
